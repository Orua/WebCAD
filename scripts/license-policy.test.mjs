import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync, existsSync} from 'node:fs';
import {resolve, dirname} from 'node:path';
import {createHash} from 'node:crypto';
import {evaluateLicensePolicy, isGeneratedPublicMaterial, auditLicensePolicy} from './license-policy.mjs';
import {QUICK_MODEL_PREVIEWS} from '../src/quick-models/preview-assets.js';

const root = resolve(import.meta.dirname, '..');
const record = (extra = {}) => ({id:'library', path:'vendor/library', component:'library', originType:'upstream',
  aiAssisted:null, sourceUrl:'https://example.org/library', commit:null, version:'1.0', licenseExpression:'MIT',
  noticePath:'LICENSES/MIT.txt', copyrightHolder:'Upstream authors', modified:false, patchEvidence:null,
  distributionScopes:['public-web'], evidenceStatus:'verified', evidence:'retained notice', ...extra});
const evaluate = (records, extra = {}) => evaluateLicensePolicy({schemaVersion:1, records}, {scope:'public-web', ...extra});

test('unresolved distributed dependencies fail; unrelated dev-only gaps do not', () => {
  assert.equal(evaluate([record({evidenceStatus:'blocked'})]).allowed, false);
  assert.equal(evaluate([record(), record({id:'dev', distributionScopes:['dev-only'], evidenceStatus:'blocked'})]).allowed, true);
});
test('actual graph activates only distributed packages and embedded components', () => {
  const records=[record(),record({id:'native',packageName:'native',evidenceStatus:'blocked'}),
    record({id:'fragment',activationModules:['node_modules/three/SVGLoader.js'],evidenceStatus:'needs-review'})];
  assert.equal(evaluate(records,{inventoryKnown:true}).allowed,true);
  const bundled=evaluate(records,{inventoryKnown:true,packages:[{name:'native',version:'1.0',declaredLicense:'MIT'}],
    moduleFiles:[{path:'node_modules/three/SVGLoader.js'}]});
  assert.ok(bundled.blockers.includes('native: blocked'));
  assert.ok(bundled.blockers.includes('fragment: needs-review'));
});
test('a new package, version drift or license drift cannot inherit approval', () => {
  const records = [record({packageName:'library'})];
  for (const pkg of [{name:'other', version:'1.0', declaredLicense:'MIT'},
    {name:'library', version:'2.0', declaredLicense:'MIT'}, {name:'library', version:'1.0', declaredLicense:'GPL-3.0'}]) {
    assert.equal(evaluate(records, {packages:[pkg]}).allowed, false);
  }
  assert.equal(evaluate(records, {packages:[{name:'library', version:'1.0', declaredLicense:'MIT'}]}).allowed, true);
});
test('copied media require exact reviewed bytes; a new file and modified WASM are rejected', () => {
  const records = [record({path:'public/test.wasm', sha256:'abc'})];
  assert.equal(evaluate(records, {copiedFiles:[{path:'public/test.wasm', sha256:'abc'}]}).allowed, true);
  for (const file of [{path:'public/test.wasm', sha256:'changed'}, {path:'public/photo.png', sha256:'abc'}])
    assert.equal(evaluate(records, {copiedFiles:[file]}).allowed, false);
});
test('known generated bytes establish provenance without granting application rights', () => {
  const records=[record({id:'previews',path:'public/previews/**',evidenceStatus:'needs-review',
    files:[{path:'public/previews/example.png',sha256:'abc'}]})];
  const known=evaluate(records,{inventoryKnown:true,copiedFiles:[{path:'public/previews/example.png',sha256:'abc'}]});
  assert.deepEqual(known.blockers,['previews: needs-review']);
  const changed=evaluate(records,{inventoryKnown:true,copiedFiles:[{path:'public/previews/example.png',sha256:'changed'}]});
  assert.ok(changed.blockers.some(message=>message.startsWith('Unapproved copied file')));
  assert.ok(evaluate(records,{inventoryKnown:true,copiedFiles:[{path:'public/previews/stale.png',sha256:'abc'}]}).blockers
    .some(message=>message.includes('stale.png')));
  assert.deepEqual(evaluate([record({id:'application-rights',evidenceStatus:'needs-review',files:[]})],
    {inventoryKnown:true}).blockers,['application-rights: needs-review']);
});
test('HDR companion text is recognized without normalizing away changed distributed bytes', () => {
  const path='render-assets/studio-small-09.LICENSE.txt';
  const sha256=createHash('sha256').update(readFileSync(resolve(root,'public',path))).digest('hex');
  const inventory={packages:[],artifacts:[{path,sha256}]};
  assert.equal(auditLicensePolicy(root,inventory,'public-web').blockers.some(message=>message.includes('Unapproved copied file')),false);
  inventory.artifacts[0].sha256='0'.repeat(64);
  assert.ok(auditLicensePolicy(root,inventory,'public-web').blockers.some(message=>message.includes('Unapproved copied file')));
});
test('generated provenance inherits only a verified in-scope rights parent',()=>{
 const parent=record({id:'application-rights',evidenceStatus:'needs-review'});
 const generated=record({id:'generated',rightsParent:'application-rights',copyrightHolder:null,licenseExpression:null,
  files:[{path:'public/generated.png',sha256:'known'}]});
 const context={inventoryKnown:true,copiedFiles:[{path:'public/generated.png',sha256:'known'}]};
 assert.equal(evaluate([parent,generated],context).allowed,false);
 assert.equal(evaluate([{...parent,evidenceStatus:'verified'},generated],context).allowed,true);
 assert.equal(evaluate([{...parent,evidenceStatus:'verified'},generated],{...context,copiedFiles:[{path:'public/generated.png',sha256:'changed'}]}).allowed,false);
 assert.equal(evaluate([generated],context).allowed,false);
});
test('unknown scopes, duplicate records and missing provenance fail closed', () => {
  assert.throws(() => evaluateLicensePolicy({schemaVersion:1, records:[]}, {scope:'public'}), /Unknown/);
  assert.throws(() => evaluate([record(), record()]), /Duplicate/);
  const incomplete = record(); delete incomplete.originType;
  assert.throws(() => evaluate([incomplete]), /Missing originType/);
  assert.equal(evaluate([record({copyrightHolder:'pending'})]).allowed, false);
  assert.equal(evaluate([record({copyrightHolder:null})]).allowed, false);
  assert.equal(evaluate([record({copyrightHolder:''})]).allowed, false);
});
test('generated text exemption does not admit arbitrary archives, JSON or media', () => {
  for (const path of ['automation/agent-bundle.zip','automation/index.html','automation/tools/box.json'])
    assert.equal(isGeneratedPublicMaterial(path),true,path);
  for (const path of ['automation/private.zip','automation/private.json','automation/photo.jpg','docs/private.md',
    'automation/remote-agent/unreviewed.js']) assert.equal(isGeneratedPublicMaterial(path),false,path);
});
test('checked-in public policy honestly remains blocked and has readable evidence', () => {
  const policy = JSON.parse(readFileSync(resolve(root, 'docs/compliance/source-license-map.json')));
  const result = evaluateLicensePolicy(policy, {scope:'public-web'});
  assert.equal(result.allowed, false);
  assert.ok(result.blockers.some(b => b.startsWith('application-rights:')));
  assert.ok(!result.blockers.some(b => b.startsWith('occt-modeling:')));assert.ok(policy.records.find(r=>r.id==='occt-modeling').engineeringVerification.nativeRebuildExecuted===false);
  assert.ok(result.blockers.some(b => b.startsWith('antique-texture:')));
  for (const r of policy.records) {
    assert.ok(existsSync(resolve(root, r.noticePath)), r.id);
    if (r.noticeNormalizedSha256) assert.equal(createHash('sha256').update(
      readFileSync(resolve(root, r.noticePath), 'utf8').replaceAll('\r\n', '\n')).digest('hex'), r.noticeNormalizedSha256, r.id);
  }
});
test('embedded notices and referenced preview provenance are precise and hash-bound', () => {
  const policy=JSON.parse(readFileSync(resolve(root,'docs/compliance/source-license-map.json')));
  const find=id=>policy.records.find(record=>record.id===id);
  assert.equal(find('string.prototype.codepointat').installedNoticePath,'node_modules/string.prototype.codepointat/LICENSE-MIT.txt');
  assert.equal(find('string.prototype.codepointat').evidenceStatus,'verified');
  assert.equal(find('earcut').version,'3.0.1');
  assert.ok(find('earcut').activationModules.includes('node_modules/three/build/three.core.js'));
  assert.equal(find('fflate-embedded').copyrightHolder,'Arjun Barrett');
  assert.equal(find('svg-numbers-embedded').copyrightHolder,'Peter-Paul van Gemerden');
  assert.equal(find('studio-hdr-notice').evidenceStatus,'verified');
  assert.equal(find('embedded-libraries'),undefined);
  const preview=find('quick-model-previews');
  assert.equal(preview.evidenceStatus,'verified');assert.equal(preview.rightsParent,'application-rights');
  assert.equal(preview.copyrightHolder,'pending');
  const expected=Object.values(QUICK_MODEL_PREVIEWS).flatMap(item=>['image','guide'].map(role=>
    ({path:'public/'+item[role],sha256:item[role+'Sha256']})));
  assert.deepEqual(preview.files.map(({path,sha256})=>({path,sha256})).sort((a,b)=>a.path.localeCompare(b.path)),
    expected.sort((a,b)=>a.path.localeCompare(b.path)));
  for(const file of preview.files) assert.equal(createHash('sha256').update(readFileSync(resolve(root,file.path))).digest('hex'),file.sha256);
  for(const file of preview.sourceFiles) assert.equal(createHash('sha256').update(
    readFileSync(resolve(root,file.path),'utf8').replaceAll('\r\n','\n')).digest('hex'),file.normalizedSha256);
});
test('new public documentation relative links resolve', () => {
  for (const path of ['README.md', 'README.en.md', 'LICENSE.md', 'CORRESPONDING_SOURCE.md', 'THIRD_PARTY_NOTICES.md', 'CONTRIBUTING.md', 'SECURITY.md', 'CHANGELOG.md',
    'docs/QUICKSTART.md', 'docs/BUILD.md', 'docs/VALIDATION.md', 'docs/PUBLIC-DEPLOYMENT.md',
    'docs/compliance/LICENSE_DECISION.md']) {
    const text = readFileSync(resolve(root, path), 'utf8');
    for (const [, link] of text.matchAll(/\[[^\]]*\]\(([^)]+)\)/g)) {
      if (/^(?:https?:|mailto:|#)/.test(link)) continue;
      assert.ok(existsSync(resolve(dirname(resolve(root, path)), link.split('#')[0])), `${path}: ${link}`);
    }
  }
});
